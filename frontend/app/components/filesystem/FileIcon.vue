.fi {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  flex-shrink: 0;
  color: var(--accent);
}

.fi-svg {
  width: 100%;
  height: 100%;
  fill: currentColor;
}

.fi-svg :deep(*) {
  fill: currentColor;
}

.fi-placeholder {
  font-family: var(--font_main);
  font-size: 0.85em;
  letter-spacing: 0.04em;
  text-transform: uppercase;
  opacity: 0.7;
}

.fi-loading .fi-placeholder { opacity: 0.4; }
.fi-fallback .fi-placeholder { opacity: 0.65; }
</style>
